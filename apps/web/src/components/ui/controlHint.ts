type State = { busy?: boolean; disabled?: boolean; description?: string }
export function controlHint(label: string, { busy, disabled, description }: State = {}) {
  if (busy) return '正在处理，请稍候。'
  if (description) return description
  if (disabled) return `“${label}”暂不可用，请先完成必填项并核对当前状态。`
  const actions: [RegExp, string][] = [
    [/复制/, '复制完整内容到剪贴板，便于粘贴使用。'],
    [/操作与功能说明/, '展开本页的功能介绍和操作步骤，再次点击可收起。'],
    [/管理讨论|管理回复/, '展开讨论或回复的管理操作，填写理由后可执行当前账号允许的操作。'],
    [/发布讨论|发布回复/, '将填写的内容发布到本课程讨论，其他有权限的成员可以阅读。'],
    [/隐藏内容/, '隐藏后普通成员无法阅读正文，原记录保留供教师处理。'],
    [/恢复内容/, '恢复内容后，有权限的课程成员可以重新阅读。'],
    [/置顶/, '切换讨论置顶状态，置顶主题优先显示。'],
    [/锁定/, '切换讨论锁定状态，锁定后停止新增回复。'],
    [/标记.*解决/, '更新讨论的解决状态，方便同学查找已解答的问题。'],
    [/登录/, '使用填写的账号和密码进入课程工作区。'],
    [/保存.*草稿|创建草稿/, '保存当前编辑为草稿，发布前仍可继续修改。'],
    [/发布/, '核对内容、影响范围和操作理由后发布。'],
    [/提交代码/, '提交当前代码进行评测，请先核对正式或练习状态。'],
    [/导出/, '下载所选数据或当前草稿到本机。'],
    [/清除筛选/, '清空当前筛选条件，重新显示已加载的全部记录。'],
    [/重试/, '重新请求当前数据，保留已有输入。'],
    [/取消|关闭|收起/, '关闭当前面板或取消这一步操作。'],
    [/返回|查看|进入|课程|学习|通知|主页|设置/, `打开“${label}”，查看相应内容或操作。`],
  ]
  return actions.find(([pattern]) => pattern.test(label))?.[1] || `点击“${label}”执行该操作。`
}

import { expect, test } from '@playwright/test'

test('普通教师可从导航修改本人密码，旧会话撤销并重新登录', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill('teacher_b')
  await page.getByLabel('密码', { exact: true }).fill('ExamplePassword123!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '修改密码', exact: true }).click()
  await expect(page.getByRole('heading', { name: '修改密码', exact: true })).toBeVisible()
  await page.getByLabel('当前密码', { exact: true }).fill('ExamplePassword123!')
  await page.getByLabel('新密码', { exact: true }).fill('ChangedPassword456!')
  await page.getByLabel('确认新密码', { exact: true }).fill('ChangedPassword456!')
  await page.getByRole('button', { name: '保存并重新登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await page.getByLabel('账号', { exact: true }).fill('teacher_b')
  await page.getByLabel('密码', { exact: true }).fill('ChangedPassword456!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('link', { name: '修改密码', exact: true }).click()
  await page.getByLabel('当前密码', { exact: true }).fill('ChangedPassword456!')
  await page.getByLabel('新密码', { exact: true }).fill('ExamplePassword123!')
  await page.getByLabel('确认新密码', { exact: true }).fill('ExamplePassword123!')
  await page.getByRole('button', { name: '保存并重新登录' }).click()
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
})
